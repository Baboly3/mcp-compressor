fn python_identifier(name: &str) -> String {
    safe_identifier(name, to_snake_case, PYTHON_RESERVED)
}

/// Escape a tool description for use inside a `"""` docstring.
///
/// Backslashes are doubled so sequences such as `\N` or `\u` in regexes and
/// Windows paths are not parsed as escapes, and every `"` is escaped so the
/// text can neither close the docstring early nor run into its closing quotes.
fn python_docstring_body(description: &str) -> String {
    description.replace('\\', "\\\\").replace('"', "\\\"")
}

fn python_params(bindings: &[ParamBinding], tool: &crate::compression::engine::Tool) -> String {
    bindings
        .iter()
        .map(|binding| {
            let hint = python_type(property_schema(tool, &binding.wire_name));
            match (binding.required, hint) {
                (true, Some(hint)) => format!("{}: {hint}", binding.identifier),
                (true, None) => binding.identifier.clone(),
                (false, Some(hint)) => format!("{}: {hint} | None = None", binding.identifier),
                (false, None) => format!("{}=None", binding.identifier),
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn property_schema<'a>(
    tool: &'a crate::compression::engine::Tool,
    name: &str,
) -> Option<&'a serde_json::Value> {
    tool.input_schema.get("properties")?.get(name)
}

/// A builtin annotation for a property, or `None` when the schema has no
/// single clear type. The module uses `from __future__ import annotations`,
/// so `int | None` is fine on any Python 3 version.
fn python_type(schema: Option<&serde_json::Value>) -> Option<&'static str> {
    use serde_json::Value;
    let schema = schema?.as_object()?;
    let ty = match schema.get("type")? {
        Value::String(ty) => ty.as_str(),
        // `["string", "null"]` is still a string; the param defaults to None.
        Value::Array(types) => {
            let mut non_null = types
                .iter()
                .filter_map(Value::as_str)
                .filter(|t| *t != "null");
            let ty = non_null.next()?;
            if non_null.next().is_some() {
                return None;
            }
            ty
        }
        _ => return None,
    };
    Some(match ty {
        "string" => "str",
        "integer" => "int",
        "number" => "float",
        "boolean" => "bool",
        "array" => "list",
        "object" => "dict",
        _ => return None,
    })
}

/// Docstring body: the tool description, then a Google-style `Args:` section
/// for documented parameters (including their allowed values, if any).
fn python_docstring(tool: &crate::compression::engine::Tool, bindings: &[ParamBinding]) -> String {
    let mut text = tool.description.as_deref().unwrap_or("").trim().to_string();
    let args: Vec<String> = bindings
        .iter()
        .filter_map(|binding| {
            let schema = property_schema(tool, &binding.wire_name)?;
            let mut description = schema
                .get("description")
                .and_then(serde_json::Value::as_str)
                .unwrap_or("")
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ");
            if let Some(values) = schema.get("enum").and_then(serde_json::Value::as_array) {
                let values = values
                    .iter()
                    .map(|value| {
                        value
                            .as_str()
                            .map_or_else(|| value.to_string(), str::to_string)
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                if !description.is_empty() {
                    description.push(' ');
                }
                description.push_str(&format!("One of: {values}."));
            }
            (!description.is_empty())
                .then(|| format!("        {}: {description}", binding.identifier))
        })
        .collect();
    if !args.is_empty() {
        if !text.is_empty() {
            text.push_str("\n\n");
        }
        text.push_str("    Args:\n");
        text.push_str(&args.join("\n"));
        text.push_str("\n    ");
    }
    python_docstring_body(&text)
}

/// Render the payload object, keeping the schema's property order on the wire.
fn python_input_dict(bindings: &[ParamBinding], tool: &crate::compression::engine::Tool) -> String {
    let schema_order = tool.param_names();
    let mut ordered: Vec<&ParamBinding> = bindings.iter().collect();
    ordered.sort_by_key(|binding| {
        schema_order
            .iter()
            .position(|name| *name == binding.wire_name)
    });
    let pairs = ordered
        .iter()
        .map(|binding| {
            format!(
                "{}: {}",
                string_literal(&binding.wire_name),
                binding.identifier
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("{{{pairs}}}")
}

fn to_snake_case(name: &str) -> String {
    let mut output = String::new();
    let mut previous_was_separator = false;
    for (index, ch) in name.chars().enumerate() {
        if ch == '-' || ch == ' ' {
            if !output.is_empty() && !previous_was_separator {
                output.push('_');
            }
            previous_was_separator = true;
        } else if ch.is_ascii_uppercase() {
            if index > 0 && !previous_was_separator {
                output.push('_');
            }
            output.push(ch.to_ascii_lowercase());
            previous_was_separator = false;
        } else {
            output.push(ch);
            previous_was_separator = ch == '_';
        }
    }
    output
}

fn ordered_param_names(tool: &crate::compression::engine::Tool) -> Vec<(String, bool)> {
    let required = required_params(tool);
    let mut params = tool
        .param_names()
        .into_iter()
        .map(|name| {
            let is_required = required.contains(&name);
            (name, is_required)
        })
        .collect::<Vec<_>>();
    params.sort_by_key(|(_name, is_required)| !*is_required);
    params
}

fn required_params(tool: &crate::compression::engine::Tool) -> Vec<String> {
    tool.input_schema
        .get("required")
        .and_then(serde_json::Value::as_array)
        .map(|values| {
            values
                .iter()
                .filter_map(serde_json::Value::as_str)
                .map(ToString::to_string)
                .collect()
        })
        .unwrap_or_default()
}

