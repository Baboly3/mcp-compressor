//! `PythonGenerator` — generates an importable Python module.
//!
//! Each upstream tool becomes a synchronous function that calls `POST /exec`
//! on the local tool proxy.  The generated module:
//!
//! - Is named `<cli_name>.py`.
//! - Uses only the standard library (`urllib`) for HTTP calls.
//! - Contains `_BRIDGE` and `_TOKEN` module-level constants.
//! - Has one `def <tool_name>(...)` function per upstream tool with:
//!   - Required params first; optional params default to `None` (omitted on the wire).
//!   - Type annotations derived from each property's JSON Schema type.
//!   - A docstring with the tool's description and an `Args:` section.
//!   - Return type annotation of `str`.
//! - Contains a `# generated by mcp-compressor — do not edit manually` header.

use crate::client_gen::generator::{
    bind_params, safe_identifier, string_literal, ClientGenerator, GeneratedArtifact,
    GeneratorConfig, ParamBinding,
};
use crate::Error;

pub struct PythonGenerator;

impl ClientGenerator for PythonGenerator {
    fn render(&self, config: &GeneratorConfig) -> Result<Vec<GeneratedArtifact>, Error> {
        Ok(vec![GeneratedArtifact::new(
            format!("{}.py", config.cli_name),
            render_python_module(config),
        )])
    }
}

fn render_python_module(config: &GeneratorConfig) -> String {
    let mut module = format!(
        r#"# generated by mcp-compressor — do not edit manually
from __future__ import annotations

import json as _json
import urllib.error as _urllib_error
import urllib.request as _urllib_request

_BRIDGE = {bridge:?}
_TOKEN = {token:?}
_SESSION_PID = {pid}
_HEADERS = {{"Content-Type": "application/json", "Authorization": f"Bearer {{_TOKEN}}"}}




def _unwrap_proxy_response(body: str) -> str:
    try:
        parsed = _json.loads(body)
    except Exception:
        return body
    if isinstance(parsed, dict) and set(parsed.keys()) == {{"result"}}:
        result = parsed["result"]
        return result if isinstance(result, str) else _json.dumps(result, separators=(",", ":"))
    return body


def _exec(tool: str, tool_input: dict) -> str:
    # Omitted optional arguments are None; leave them out like the CLI and TS clients do.
    tool_input = {{key: value for key, value in tool_input.items() if value is not None}}
    payload = _json.dumps({{"tool": tool, "input": tool_input}}).encode()
    request = _urllib_request.Request(_BRIDGE + "/exec", data=payload, headers=_HEADERS, method="POST")
    try:
        with _urllib_request.urlopen(request) as response:
            return _unwrap_proxy_response(response.read().decode())
    except _urllib_error.HTTPError as exc:
        body = exc.read().decode(errors="replace")
        try:
            parsed = _json.loads(body)
        except Exception:
            parsed = None
        if isinstance(parsed, dict) and isinstance(parsed.get("error"), str):
            raise RuntimeError(parsed["error"]) from None
        raise RuntimeError(
            f"mcp-compressor proxy returned HTTP {{exc.code}}: {{body or exc.reason}}"
        ) from None
    except OSError as exc:
        details = getattr(exc, "reason", exc)
        raise RuntimeError(
            "mcp-compressor proxy is not running; restart the mcp-compressor process and try again. "
            f"details: {{details}}"
        ) from None
"#,
        bridge = config.bridge_url,
        token = config.token,
        pid = config.session_pid,
    );

    for tool in &config.tools {
        let bindings = bind_params(ordered_param_names(tool), python_identifier);
        module.push_str(&format!(
            r#"

def {name}({params}) -> str:
    """{docstring}"""
    return _exec({tool_name}, {input})
"#,
            name = python_identifier(&tool.name),
            params = python_params(&bindings, tool),
            docstring = python_docstring(tool, &bindings),
            tool_name = string_literal(&tool.name),
            input = python_input_dict(&bindings, tool),
        ));
    }

    module
}

